# --- edit scope -----------------------------------------------------------------------

def looks_generated(head: str) -> bool:
    """True when the first 512 characters carry a generated-file marker."""
    sample = str(head or "")[:512].lower()
    return any(marker in sample for marker in GENERATED_MARKERS)


@dataclass(frozen=True, slots=True)
class EditScope:
    roots: tuple[str, ...]
    suffixes: frozenset[str] = DEFAULT_EDITABLE_SUFFIXES
    denied_names: frozenset[str] = DENIED_NAMES
    globs: tuple[str, ...] = ()
    excluded_rel: frozenset[str] = frozenset()
    generated_rel: frozenset[str] = frozenset()
    excluded_dirs: tuple[str, ...] = ()
    max_file_bytes: int = MAX_FILE_BYTES

    def __post_init__(self) -> None:
        if not self.roots or len(self.roots) != 1:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "edit scope is the project source root only")
        if len(self.globs) > MAX_GLOBS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "at most %d editable globs" % MAX_GLOBS)
        for glob in self.globs:
            if not isinstance(glob, str) or not glob or len(glob) > MAX_GLOB_CHARS \
                    or "\x00" in glob or glob.startswith(("/", "\\")) or ".." in glob.split("/") \
                    or re.match(r"^[A-Za-z]:", glob):
                raise BuildDomainError("FIX_SCOPE_REJECTED", "editable globs must be relative")
        if not 1 <= int(self.max_file_bytes) <= MAX_FILE_BYTES:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "max_file_bytes is capped at 2 MiB")

    def allows(self, rel: str) -> tuple[bool, str]:
        """(allowed, reason); reason is a FixStopReason-compatible code when refused."""
        normalized = safe_rel(rel)
        if normalized is None:
            return False, "OUT_OF_SCOPE_FILE"
        parts = normalized.split("/")
        lower = parts[-1].lower()
        if any(part.lower() in DENIED_DIRS for part in parts[:-1]):
            return False, "OUT_OF_SCOPE_FILE"
        for directory in self.excluded_dirs:
            prefix = directory.rstrip("/")
            if prefix and (normalized == prefix or normalized.startswith(prefix + "/")):
                return False, "OUT_OF_SCOPE_FILE"
        if normalized in self.excluded_rel:
            return False, "BUILD_TIME_TOOL_SOURCE"
        suffix = posixpath.splitext(lower)[1]
        if lower in BUILD_SCRIPT_NAMES or suffix in BUILD_SCRIPT_SUFFIXES:
            return False, "NEEDS_BUILD_SCRIPT_CHANGE"
        if lower in {name.lower() for name in self.denied_names} or lower.startswith(".env"):
            return False, "OUT_OF_SCOPE_FILE"
        if normalized in self.generated_rel or ".generated." in lower:
            return False, "OUT_OF_SCOPE_FILE"
        if suffix not in self.suffixes:
            return False, "OUT_OF_SCOPE_FILE"
        if self.globs and not any(_glob_match(normalized, glob) for glob in self.globs):
            return False, "OUT_OF_SCOPE_FILE"
        return True, ""

    def digest(self) -> str:
        payload = {
            "roots": list(self.roots), "suffixes": sorted(self.suffixes),
            "denied": sorted(self.denied_names), "globs": list(self.globs),
            "excluded": sorted(self.excluded_rel), "generated": sorted(self.generated_rel),
            "excluded_dirs": list(self.excluded_dirs), "max": int(self.max_file_bytes),
        }
        material = json.dumps(payload, sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(material.encode("utf-8")).hexdigest()


def _glob_match(rel: str, glob: str) -> bool:
    pattern = glob.replace("\\", "/")
    if "**" in pattern:
        regex = re.escape(pattern).replace(r"\*\*/", "(?:.*/)?").replace(r"\*\*", ".*")
        regex = regex.replace(r"\*", "[^/]*").replace(r"\?", "[^/]")
        return re.fullmatch(regex, rel) is not None
    return fnmatch.fnmatchcase(rel, pattern)


# --- normalization and hostile scan -------------------------------------------------

_RAW_PREFIX_RE = re.compile(r'(?:u8|u|U|L)?R"([^()\\\s"]{0,16})\(')


def normalize_for_scan(text: str) -> str:
    """Translation phases 1-3 as far as the scan needs them.

    Trigraphs ``??=`` and ``??/`` are replaced, backslash-newline splices are
    joined, digraphs ``%:%:``/``%:`` become ``##``/``#``, comments become a
    space, and raw-string bodies are masked (their newlines kept) so text
    inside them cannot pose as a directive. Ordinary string contents are
    kept: ``_Pragma("...")`` and ``asm("...")`` arguments must stay visible.
    """
    value = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    value = value.replace("??=", "#").replace("??/", "\\")
    value = re.sub(r"\\[ \t]*\n", "", value)
    value = value.replace("%:%:", "##").replace("%:", "#")
    out: list[str] = []
    i = 0
    n = len(value)
    while i < n:
        ch = value[i]
        if ch == "/" and i + 1 < n and value[i + 1] == "/":
            end = value.find("\n", i)
            out.append(" ")
            i = n if end < 0 else end
            continue
        if ch == "/" and i + 1 < n and value[i + 1] == "*":
            end = value.find("*/", i + 2)
            out.append(" ")
            i = n if end < 0 else end + 2
            continue
        if ch in "uUL8R":
            raw = _RAW_PREFIX_RE.match(value, i)
            if raw and (i == 0 or not (value[i - 1].isalnum() or value[i - 1] == "_")):
                delimiter = ")" + raw.group(1) + '"'
                start = raw.end()
                end = value.find(delimiter, start)
                end = n if end < 0 else end
                body = value[start:end]
                out.append(value[i:start])
                out.append("".join("\n" if c == "\n" else "x" for c in body))
                out.append(delimiter if end < n else "")
                i = end + len(delimiter) if end < n else n
                continue
        if ch in "\"'":
            quote = ch
            j = i + 1
            while j < n and value[j] != quote and value[j] != "\n":
                j += 2 if value[j] == "\\" else 1
            out.append(value[i:min(j + 1, n)])
            i = j + 1
            continue
        out.append(ch)
        i += 1
    return "".join(out)


_DIRECTIVE_RE = re.compile(r"^\s*#\s*([A-Za-z_]\w*)\s*(.*)$")
_PRAGMA_BAD_RE = re.compile(
    r"\b(?:comment\s*\(\s*(?:linker|lib|user)\b|include_alias|section|init_seg|code_seg|"
    r"data_seg|const_seg|bss_seg|alloc_text|detect_mismatch)\b|\bGCC\s+poison\b|"
    r"\bclang\s+(?:section|attribute)\b",
    re.IGNORECASE,
)
_PRAGMA_OP_RE = re.compile(r"\b_Pragma\s*\(")
_MS_PRAGMA_RE = re.compile(r"\b__pragma\s*\(")
_HAS_RE = re.compile(r"\b__has_(?:include(?:_next)?|embed)\s*\(\s*([<\"])")
_ASM_RE = re.compile(r"\b(?:asm|__asm__|__asm)\b")
_ASM_DIRECTIVE_RE = re.compile(r"(?:^|[\s;\"'])\.(?:incbin|include|file|section|pushsection|"
                               r"init_array|fini_array|ctors|dtors)\b")
_ATTRIBUTE_RE = re.compile(r"\b__attribute__\s*\(\(")
_ATTR_BAD_RE = re.compile(r"\b_{0,2}(?:section|constructor|destructor|ifunc|alias|weakref|"
                          r"init_priority)_{0,2}\b")
_CXX_ATTR_RE = re.compile(r"\[\[\s*(?:gnu|clang)\s*::\s*_{0,2}(?:section|constructor|destructor|"
                          r"ifunc|alias|weakref|init_priority)")
_DECLSPEC_RE = re.compile(r"\b__declspec\s*\(\s*(?:allocate|code_seg)\b")
_STRING_RE = re.compile(r'"(?:[^"\\\n]|\\.)*"')


def _balanced(text: str, start: int, limit: int = 4096) -> str:
    """Text from ``start`` (just after an opening paren) to its closing paren."""
    depth = 1
    i = start
    end = min(len(text), start + limit)
    quote = ""
    while i < end:
        ch = text[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return text[start:i]
        i += 1
    return text[start:end]


def _unescape(literal: str) -> str:
    body = literal[1:-1] if len(literal) >= 2 else literal
    return body.replace('\\"', '"').replace("\\\\", "\\")


def include_path_problem(path: str, *, quoted: bool) -> str:
    """Why an include path is refused ('' when acceptable), before containment."""
    if not path or "\x00" in path:
        return "empty include path"
    text = path.replace("\\", "/")
    if text.startswith("/") or re.match(r"^[A-Za-z]:", text) or text.startswith("//"):
        return "absolute include path"
    suffix = posixpath.splitext(posixpath.basename(text))[1].lower()
    if suffix:
        if suffix not in INCLUDE_SUFFIXES:
            return "include of a non-header file"
    elif quoted:
        return "quoted include without a header suffix"
    if not quoted and ".." in text.split("/"):
        return "system include escaping upward"
    return ""


def _include_target(rest: str) -> tuple[str, bool] | None:
    rest = rest.strip()
    if rest.startswith('"'):
        end = rest.find('"', 1)
        return (rest[1:end], True) if end > 0 else None
    if rest.startswith("<"):
        end = rest.find(">", 1)
        return (rest[1:end], False) if end > 0 else None
    return None


def scan_hostile_directives(added_text: str, *,
                            include_ok: Callable[[str], bool]) -> tuple[str, ...]:
    """Reasons the added (already normalized) logical lines are refused.

    ``include_ok(path)`` decides containment of a quoted include relative to
    the edited file (it must refuse ``..`` escaping the project root).
    """
    reasons: list[str] = []

    def refuse(reason: str) -> None:
        if reason not in reasons:
            reasons.append(reason)

    text = str(added_text or "")
    for line in text.split("\n"):
        directive = _DIRECTIVE_RE.match(line)
        if not directive:
            continue
        name, rest = directive.group(1), directive.group(2)
        if name in ("include", "include_next", "import"):
            if name == "import":
                refuse("#import is refused")
                continue
            target = _include_target(rest)
            if target is None:
                refuse("computed #include is refused")
                continue
            path, quoted = target
            problem = include_path_problem(path, quoted=quoted)
            if problem:
                refuse(problem)
            elif quoted and not include_ok(path):
                refuse("include escapes the project root")
        elif name == "using":
            refuse("#using is refused")
        elif name == "embed":
            refuse("#embed is refused")
        elif name == "line":
            refuse("#line is refused (it redirects later diagnostics)")
        elif name == "pragma":
            if _PRAGMA_BAD_RE.search(rest):
                refuse("#pragma %s is refused" % clip(rest.split("(")[0].strip(), 40))
    for match in _PRAGMA_OP_RE.finditer(text):
        body = _balanced(text, match.end())
        literals = _STRING_RE.findall(body)
        if not literals:
            refuse("_Pragma without a string literal is refused")
            continue
        if _PRAGMA_BAD_RE.search(" ".join(_unescape(item) for item in literals)):
            refuse("_Pragma with a linker/section directive is refused")
    for match in _MS_PRAGMA_RE.finditer(text):
        if _PRAGMA_BAD_RE.search(_balanced(text, match.end())):
            refuse("__pragma with a linker/section directive is refused")
    for match in _HAS_RE.finditer(text):
        quoted = match.group(1) == '"'
        closer = '"' if quoted else ">"
        start = match.end()
        end = text.find(closer, start)
        path = text[start:end] if end > start else ""
        problem = include_path_problem(path, quoted=quoted) if path else "computed __has_include"
        if not problem and quoted and not include_ok(path):
            problem = "include escapes the project root"
        if problem:
            refuse("__has_include/__has_embed: " + problem)
    for match in _ASM_RE.finditer(text):
        window = text[match.end(): match.end() + 4096]
        paren = window.find("(")
        brace = window.find("{")
        if paren >= 0 and (brace < 0 or paren < brace):
            body = _balanced(window, paren + 1)
        elif brace >= 0:
            end = window.find("}", brace)
            body = window[brace: end if end > 0 else len(window)]
        else:
            body = window[:256]
        if _ASM_DIRECTIVE_RE.search(body.replace("\\n", "\n").replace("\\t", " ")):
            refuse("inline assembly with an assembler file/section directive is refused")
    for literal in _STRING_RE.findall(text):
        if _ASM_DIRECTIVE_RE.search(_unescape(literal).replace("\\n", "\n").replace("\\t", " ")):
            refuse("string literal carrying an assembler directive is refused")
            break
    for match in _ATTRIBUTE_RE.finditer(text):
        if _ATTR_BAD_RE.search(_balanced(text, match.end())):
            refuse("__attribute__ section/constructor/destructor is refused")
    if _CXX_ATTR_RE.search(text):
        refuse("[[gnu::section/constructor/destructor]] is refused")
    if _DECLSPEC_RE.search(text):
        refuse("__declspec(allocate/code_seg) is refused")
    growth = sum(len(item) - 2 for item in _STRING_RE.findall(text))
    if growth > MAX_STRING_GROWTH:
        refuse("string literal growth above 64 KiB is refused")
    return tuple(reasons)


def added_logical_lines(before: str, after: str) -> str:
    """Normalized logical lines present in ``after`` but not in ``before`` (multiset)."""
    old = normalize_for_scan(before).split("\n")
    new = normalize_for_scan(after).split("\n")
    counts: dict[str, int] = {}
    for line in old:
        counts[line] = counts.get(line, 0) + 1
    added: list[str] = []
    for line in new:
        if counts.get(line, 0) > 0:
            counts[line] -= 1
        else:
            added.append(line)
    return "\n".join(added)


# --- patches ------------------------------------------------------------------------

@dataclass(frozen=True, slots=True)
class PatchHunk:
    file_rel: str
    anchor: str
    replacement: str

    def __post_init__(self) -> None:
        if not isinstance(self.file_rel, str) or safe_rel(self.file_rel) is None:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk file must be source-relative")
        if not isinstance(self.anchor, str) or not 1 <= len(self.anchor) <= MAX_ANCHOR_CHARS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk anchor must be 1..4000 characters")
        if not isinstance(self.replacement, str) or len(self.replacement) > MAX_REPLACEMENT_CHARS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk replacement exceeds 8000 characters")
        if "\x00" in self.anchor or "\x00" in self.replacement:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk contains NUL")


@dataclass(frozen=True, slots=True)
class CandidatePatch:
    hunks: tuple[PatchHunk, ...]
    rationale: str = ""
    model_id: str = ""

    def __post_init__(self) -> None:
        if not isinstance(self.hunks, tuple) or not 1 <= len(self.hunks) <= MAX_HUNKS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "a patch has 1..8 hunks")
        if any(not isinstance(item, PatchHunk) for item in self.hunks):
            raise BuildDomainError("FIX_SCOPE_REJECTED", "a patch holds PatchHunk items")
        if not isinstance(self.rationale, str) or len(self.rationale) > MAX_RATIONALE_CHARS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "rationale exceeds 600 characters")
        if not isinstance(self.model_id, str) or len(self.model_id) > 200:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "model id is bounded")

    def files(self) -> tuple[str, ...]:
        out: list[str] = []
        for hunk in self.hunks:
            rel = safe_rel(hunk.file_rel) or hunk.file_rel
            if rel not in out:
                out.append(rel)
        return tuple(out)


def parse_candidate_patch(text: str, *, model_id: str = "") -> CandidatePatch:
    """Strict JSON answer ``{"hunks":[{"file","anchor","replace"}],"rationale"}``."""
    if not isinstance(text, str) or len(text) > 200_000:
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer is not bounded text")
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```(?:json)?\s*|\s*```$", "", stripped)
    try:
        document = json.loads(stripped)
    except ValueError as exc:
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer is not JSON") from exc
    if not isinstance(document, dict) or set(document) - {"hunks", "rationale"}:
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer has unexpected fields")
    hunks_raw = document.get("hunks")
    if not isinstance(hunks_raw, list):
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer needs hunks")
    hunks: list[PatchHunk] = []
    for item in hunks_raw[: MAX_HUNKS + 1]:
        if not isinstance(item, dict) or set(item) - {"file", "anchor", "replace"}:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk has unexpected fields")
        if not all(isinstance(item.get(key), str) for key in ("file", "anchor", "replace")):
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk fields must be strings")
        hunks.append(PatchHunk(file_rel=item["file"], anchor=item["anchor"],
                               replacement=item["replace"]))
    rationale = document.get("rationale", "")
    return CandidatePatch(hunks=tuple(hunks),
                          rationale=rationale if isinstance(rationale, str) else "",
                          model_id=clip(model_id, 200))


def include_checker(scope: EditScope, file_rel: str) -> Callable[[str], bool]:
    """``include_ok`` for one edited file: quoted includes stay inside the root."""
    base = posixpath.dirname(safe_rel(file_rel) or "")

    def ok(path: str) -> bool:
        joined = posixpath.join(base, path.replace("\\", "/")) if base else path.replace("\\", "/")
        return safe_rel(joined) is not None

    return ok


def _changed_lines(before: str, after: str) -> int:
    old = before.splitlines()
    new = after.splitlines()
    changed = 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, old, new, autojunk=False).get_opcodes():
        if tag != "equal":
            changed += max(i2 - i1, j2 - j1)
    return changed


def validate_patch(
    patch: CandidatePatch,
    *,
    scope: EditScope,
    current: Mapping[str, str],
    max_changed_lines: int = MAX_PATCH_CHANGED_LINES,
    loop_changed_lines_used: int = 0,
    loop_files_used: frozenset[str] | tuple[str, ...] = frozenset(),
    max_loop_changed_lines: int = MAX_LOOP_CHANGED_LINES,
    max_loop_files: int = MAX_LOOP_FILES,
) -> tuple[dict[str, str], tuple[str, ...]]:
    """Apply a candidate in memory and check it; ``({}, reasons)`` when refused.

    ``current`` maps each file the loop read to its present text. Every hunk
    anchor must occur exactly once (after earlier hunks to the same file).
    """
    reasons: list[str] = []
    texts: dict[str, str] = {}
    for hunk in patch.hunks:
        rel = safe_rel(hunk.file_rel)
        if rel is None:
            reasons.append("OUT_OF_SCOPE_FILE: %s" % clip(hunk.file_rel, 120))
            continue
        allowed, why = scope.allows(rel)
        if not allowed:
            reasons.append("%s: %s" % (why, rel))
            continue
        if rel not in texts:
            if rel not in current:
                reasons.append("OUT_OF_SCOPE_FILE: %s was not read by the loop" % rel)
                continue
            texts[rel] = current[rel]
            if looks_generated(texts[rel]):
                reasons.append("OUT_OF_SCOPE_FILE: %s is marked generated" % rel)
                continue
        occurrences = texts[rel].count(hunk.anchor)
        if occurrences != 1:
            reasons.append("ANCHOR_%s: %s" % ("MISSING" if occurrences == 0 else "AMBIGUOUS", rel))
            continue
        texts[rel] = texts[rel].replace(hunk.anchor, hunk.replacement, 1)
    changed_total = 0
    for rel, new_text in texts.items():
        before = current.get(rel, "")
        if len(new_text.encode("utf-8", "replace")) > scope.max_file_bytes:
            reasons.append("FILE_TOO_LARGE: %s" % rel)
        changed_total += _changed_lines(before, new_text)
        added = added_logical_lines(before, new_text)
        for reason in scan_hostile_directives(added, include_ok=include_checker(scope, rel)):
            reasons.append("HOSTILE_DIRECTIVE: %s: %s" % (rel, reason))
    touched = set(loop_files_used) | {rel for rel, text in texts.items() if text != current.get(rel)}
    if changed_total > max_changed_lines:
        reasons.append("BUDGET: patch changes %d lines (max %d)" % (changed_total, max_changed_lines))
    if loop_changed_lines_used + changed_total > max_loop_changed_lines:
        reasons.append("BUDGET: loop would change %d lines (max %d)"
                       % (loop_changed_lines_used + changed_total, max_loop_changed_lines))
    if len(touched) > max_loop_files:
        reasons.append("BUDGET: loop would touch %d files (max %d)" % (len(touched), max_loop_files))
    if not reasons and all(text == current.get(rel) for rel, text in texts.items()):
        reasons.append("NO_CHANGE: the candidate does not change any file")
    if reasons:
        return {}, tuple(reasons[:32])
    return {rel: text for rel, text in texts.items() if text != current.get(rel)}, ()


