class FixStopReason(str, Enum):
    FIXED = "FIXED"
    ATTEMPTS_EXHAUSTED = "ATTEMPTS_EXHAUSTED"
    NO_PROGRESS = "NO_PROGRESS"
    BUILD_DID_NOT_RUN = "BUILD_DID_NOT_RUN"
    NEEDS_BUILD_SCRIPT_CHANGE = "NEEDS_BUILD_SCRIPT_CHANGE"
    OUT_OF_SCOPE_FILE = "OUT_OF_SCOPE_FILE"
    BUILD_TIME_TOOL_SOURCE = "BUILD_TIME_TOOL_SOURCE"
    UNCERTAIN_SIDE_EFFECT = "UNCERTAIN_SIDE_EFFECT"
    CANCELLED = "CANCELLED"
    BUDGET_EXHAUSTED = "BUDGET_EXHAUSTED"
    STRATEGY_FAIL = "STRATEGY_FAIL"
    PERMISSION_DENIED = "PERMISSION_DENIED"
    RESIDENCY_REFUSED = "RESIDENCY_REFUSED"


FIX_STATUSES = frozenset({"fixed", "improved", "unchanged", "aborted", "interrupted"})
VERIFICATION_SCOPES = frozenset({"compile_one", "target", "target+dependents"})


@dataclass(frozen=True, slots=True)
class FixAttemptRecord:
    n: int
    files: tuple[str, ...]
    outcome: str
    progress: BuildProgress | None
    build_job_id: str = ""
    reasons: tuple[str, ...] = ()
    action: str = ""
    effect_intent_ids: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class FileChange:
    rel: str
    before_sha256: str
    after_sha256: str
    diff: str = ""


def sha256_text(text: str) -> str:
    return hashlib.sha256(str(text).encode("utf-8", "surrogatepass")).hexdigest()


def make_file_changes(pairs: tuple[tuple[str, str, str], ...], *,
                      max_diff_bytes: int = MAX_DIFF_BYTES) -> tuple[FileChange, ...]:
    """(rel, before, after) -> FileChange with unified diffs sharing a 16 KiB budget."""
    budget = max(0, min(int(max_diff_bytes), MAX_DIFF_BYTES))
    out: list[FileChange] = []
    for rel, before, after in pairs:
        diff = "".join(difflib.unified_diff(
            before.splitlines(keepends=True), after.splitlines(keepends=True),
            fromfile="a/" + rel, tofile="b/" + rel, n=2,
        ))
        encoded = diff.encode("utf-8", "replace")
        if len(encoded) > budget:
            diff = encoded[:budget].decode("utf-8", "ignore")
            if budget:
                diff += "\n[diff truncated]\n" if budget > 20 else ""
        budget = max(0, budget - len(diff.encode("utf-8", "replace")))
        out.append(FileChange(rel=rel, before_sha256=sha256_text(before),
                              after_sha256=sha256_text(after), diff=diff))
    return tuple(out)


@dataclass(frozen=True, slots=True)
class BuildFixReport:
    status: str
    stop_reason: FixStopReason
    job_id: str
    target: str
    config: str = ""
    verification_scope: str = "compile_one"
    attempts: tuple[FixAttemptRecord, ...] = ()
    initial: BuildProgress | None = None
    best: BuildProgress | None = None
    applied: bool = False
    revert_after: bool = False
    files: tuple[FileChange, ...] = ()
    final_build: BuildJobReport | None = None
    world: str = "host"
    network: str = "advisory_off"
    isolation_truth: str = "unverified"
    preimage_label: str = ""
    notes: tuple[str, ...] = field(default_factory=tuple)
    digest: str = ""

    def __post_init__(self) -> None:
        if self.status not in FIX_STATUSES:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "unknown fix status")
        if not isinstance(self.stop_reason, FixStopReason):
            raise BuildDomainError("FIX_SCOPE_REJECTED", "stop_reason must be FixStopReason")
        if self.verification_scope not in VERIFICATION_SCOPES:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "unknown verification scope")
        if self.isolation_truth not in ("unverified", "failure_isolation_only"):
            raise BuildDomainError("FIX_SCOPE_REJECTED", "isolation_truth must be an EXEC-006 label")
        if len(self.attempts) > 8 or len(self.files) > MAX_LOOP_FILES * 2:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "fix report lists exceed their bounds")


def _attempt_wire(item: FixAttemptRecord) -> dict:
    return {
        "n": item.n, "files": list(item.files), "outcome": item.outcome,
        "progress": progress_to_wire(item.progress), "build_job_id": item.build_job_id,
        "reasons": list(item.reasons), "action": item.action,
        "effect_intent_ids": list(item.effect_intent_ids),
    }


def fix_report_to_wire(report: BuildFixReport, *, max_bytes: int = 48_000) -> dict:
    budget = max(4096, min(int(max_bytes), 48_000))
    wire = {
        "object": "build_fix_report",
        "status": report.status,
        "stop_reason": report.stop_reason.value,
        "job_id": report.job_id,
        "target": report.target,
        "config": report.config,
        "verification_scope": report.verification_scope,
        "attempts": [_attempt_wire(item) for item in report.attempts],
        "initial": progress_to_wire(report.initial),
        "best": progress_to_wire(report.best),
        "applied": report.applied,
        "revert_after": report.revert_after,
        "files": [{"rel": item.rel, "before_sha256": item.before_sha256,
                   "after_sha256": item.after_sha256, "diff": item.diff} for item in report.files],
        "final_build": None,
        "world": report.world,
        "network": report.network,
        "isolation_truth": report.isolation_truth,
        "preimage_label": report.preimage_label,
        "notes": list(report.notes),
        "digest": report.digest,
    }
    used = len(json.dumps(wire, ensure_ascii=False).encode("utf-8"))
    if report.final_build is not None:
        wire["final_build"] = build_report_to_wire(report.final_build,
                                                   max_bytes=max(4096, budget - used))
    while len(json.dumps(wire, ensure_ascii=False).encode("utf-8")) > budget:
        trimmed = False
        for item in wire["files"]:
            if item["diff"]:
                item["diff"] = ""
                trimmed = True
                break
        if not trimmed and wire["final_build"] is not None:
            wire["final_build"] = None
            trimmed = True
        if not trimmed and wire["notes"]:
            wire["notes"].pop()
            trimmed = True
        if not trimmed:
            break
    return wire


def fix_report_digest(report: BuildFixReport) -> str:
    wire = fix_report_to_wire(replace(report, digest=""))
    material = json.dumps(wire, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def make_fix_report(**fields) -> BuildFixReport:
    fields["notes"] = bounded_notes(fields.get("notes", ()))
    report = BuildFixReport(**fields)
    return replace(report, digest=fix_report_digest(report))


