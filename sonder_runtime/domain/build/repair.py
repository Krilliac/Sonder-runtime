# --- edit scope -----------------------------------------------------------------------

def looks_generated(head: str) -> bool:
    """True when the first 512 characters carry a generated-file marker."""
    sample = str(head or "")[:512].lower()
    return any(marker in sample for marker in GENERATED_MARKERS)


@dataclass(frozen=True, slots=True)
class EditScope:
    roots: tuple[str, ...]
    suffixes: frozenset[str] = DEFAULT_EDITABLE_SUFFIXES
    denied_names: frozenset[str] = DENIED_NAMES
    globs: tuple[str, ...] = ()
    excluded_rel: frozenset[str] = frozenset()
    generated_rel: frozenset[str] = frozenset()
    excluded_dirs: tuple[str, ...] = ()
    max_file_bytes: int = MAX_FILE_BYTES

    def __post_init__(self) -> None:
        if not self.roots or len(self.roots) != 1:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "edit scope is the project source root only")
        if len(self.globs) > MAX_GLOBS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "at most %d editable globs" % MAX_GLOBS)
        for glob in self.globs:
            if not isinstance(glob, str) or not glob or len(glob) > MAX_GLOB_CHARS \
                    or "\x00" in glob or glob.startswith(("/", "\\")) or ".." in glob.split("/") \
                    or re.match(r"^[A-Za-z]:", glob):
                raise BuildDomainError("FIX_SCOPE_REJECTED", "editable globs must be relative")
        if not 1 <= int(self.max_file_bytes) <= MAX_FILE_BYTES:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "max_file_bytes is capped at 2 MiB")

    def allows(self, rel: str) -> tuple[bool, str]:
        """(allowed, reason); reason is a FixStopReason-compatible code when refused."""
        normalized = safe_rel(rel)
        if normalized is None:
            return False, "OUT_OF_SCOPE_FILE"
        parts = normalized.split("/")
        # Windows aliases would let one file pass under another name: a drive
        # (``C:x.cpp`` is drive-relative), an alternate data stream, trailing
        # dots/spaces, 8.3 short names (``SHADER~1.CPP``) and device names.
        for part in parts:
            if ":" in part or part != part.rstrip(". ") or _SHORT_NAME_RE.search(part) \
                    or part.split(".", 1)[0].upper() in _WINDOWS_DEVICE_NAMES:
                return False, "OUT_OF_SCOPE_FILE"
        # Exclusions compare case-insensitively: Windows and macOS file
        # systems would otherwise open ``Tools/ShaderGen.cpp`` for an
        # excluded ``tools/shadergen.cpp``.
        folded = normalized.casefold()
        lower = parts[-1].lower()
        if any(part.lower() in DENIED_DIRS for part in parts[:-1]):
            return False, "OUT_OF_SCOPE_FILE"
        for directory in self.excluded_dirs:
            prefix = directory.rstrip("/").casefold()
            if prefix and (folded == prefix or folded.startswith(prefix + "/")):
                return False, "OUT_OF_SCOPE_FILE"
        if folded in {item.casefold() for item in self.excluded_rel}:
            return False, "BUILD_TIME_TOOL_SOURCE"
        suffix = posixpath.splitext(lower)[1]
        if lower in BUILD_SCRIPT_NAMES or suffix in BUILD_SCRIPT_SUFFIXES:
            return False, "NEEDS_BUILD_SCRIPT_CHANGE"
        if lower in {name.lower() for name in self.denied_names} or lower.startswith(".env"):
            return False, "OUT_OF_SCOPE_FILE"
        if folded in {item.casefold() for item in self.generated_rel} or ".generated." in lower:
            return False, "OUT_OF_SCOPE_FILE"
        if suffix not in self.suffixes:
            return False, "OUT_OF_SCOPE_FILE"
        if self.globs and not any(_glob_match(normalized, glob) for glob in self.globs):
            return False, "OUT_OF_SCOPE_FILE"
        return True, ""

    def digest(self) -> str:
        payload = {
            "roots": list(self.roots), "suffixes": sorted(self.suffixes),
            "denied": sorted(self.denied_names), "globs": list(self.globs),
            "excluded": sorted(self.excluded_rel), "generated": sorted(self.generated_rel),
            "excluded_dirs": list(self.excluded_dirs), "max": int(self.max_file_bytes),
        }
        material = json.dumps(payload, sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(material.encode("utf-8")).hexdigest()


def _glob_match(rel: str, glob: str) -> bool:
    pattern = glob.replace("\\", "/")
    if "**" in pattern:
        regex = re.escape(pattern).replace(r"\*\*/", "(?:.*/)?").replace(r"\*\*", ".*")
        regex = regex.replace(r"\*", "[^/]*").replace(r"\?", "[^/]")
        return re.fullmatch(regex, rel) is not None
    return fnmatch.fnmatchcase(rel, pattern)


# --- normalization and hostile scan -------------------------------------------------

_TRIGRAPHS = {"=": "#", "/": "\\", "'": "^", "(": "[", ")": "]", "!": "|", "<": "{", ">": "}", "-": "~"}
_TRIGRAPH_RE = re.compile(r"\?\?([=/'()!<>-])")
# gcc and clang accept blanks (space, tab, form feed, vertical tab) between the
# backslash and the newline of a line splice; MSVC does not splice there (the
# next line stays a line of its own). CRLF/CR are already folded to LF.
_SPLICE_RE = re.compile(r"\\[ \t\f\v]*\n")
_STRICT_SPLICE = "\\\n"
_LEGACY_SPLICE_RE = re.compile(r"\\[ \t]*\n")
# A backslash (or its trigraph) with blanks before the newline: the only text
# the splice readings lex differently.
_BLANK_SPLICE_RE = re.compile(r"(?:\\|\?\?/)([ \t\f\v]+)\n")
_DIGRAPH_PAIRS = ("<:", ":>", "<%", "%>", "%:")
_RAW_OPEN_RE = re.compile(r'(?:u8|u|U|L)?R"')
# Raw-string delimiter characters gcc, clang and MSVC all accept. Anything else
# (a blank, ``$``, ``@``, a backquote, ``"``, a non-ASCII character, more than
# 16 characters) is an error each compiler recovers from differently: gcc and
# clang lex on to the next ``"`` (across lines), MSVC keeps a raw string with
# another delimiter. No single reading covers that, so such a prefix is refused.
_RAW_PREFIX_RE = re.compile(r"""(?:u8|u|U|L)?R"([A-Za-z0-9_{}\[\]#<>%:;.?*+\-/^&|~!=,']{0,16})\(""")
# The delimiter rule before the fix above; the "legacy" masking keeps it.
_LEGACY_RAW_PREFIX_RE = re.compile(r'(?:u8|u|U|L)?R"([^()\\\s"]{0,16})\(')


def normalize_for_scan(text: str, *, raw_strings: bool = True, trigraphs: bool = True,
                       digraphs: bool = True, strict_splices: bool = False,
                       legacy: bool = False, separators: str = "cxx14") -> str:
    """Translation phases 1-3 as far as the scan needs them.

    All nine trigraphs are replaced, backslash-newline splices (blanks between
    the backslash and the newline included) are joined, the digraphs
    ``%:%:``/``%:``/``<:``/``:>``/``<%``/``%>`` become ``##``/``#``/``[``/``]``/
    ``{``/``}`` (``<::`` not followed by ``:`` or ``>`` stays ``<`` ``::``),
    comments become a space, and raw-string bodies are masked (their newlines kept) so text
    inside them cannot pose as a directive. Ordinary string contents are
    kept: ``_Pragma("...")`` and ``asm("...")`` arguments must stay visible.

    ``raw_strings=False`` lexes ``R"(`` as C does (identifier + ordinary
    string): in C, or in a header a C TU includes, masking a "raw string"
    could hide real directives, so ``validate_patch`` scans both lexings.
    ``trigraphs=False`` leaves ``??/`` and friends alone, as gcc, clang and
    MSVC do by default (only ``-trigraphs``/``-std=c++14`` and older apply
    them); ``digraphs=False`` leaves ``<:``/``<%`` alone so a header-name
    such as ``<:/../x.h>`` is seen as written. ``strict_splices=True`` joins
    only a backslash directly followed by the newline, as MSVC does: with a
    blank in between, the lenient (gcc/clang) reading lets a ``//`` comment
    swallow the next line while MSVC compiles that line. No reading is safe
    to assume, so ``scan_added_lexings`` scans every combination and unions
    the reasons.
    ``legacy=True`` is the one reading this scanner had before those modes
    existed (only ``??=`` and ``??/``, splices across space and tab, ``%:``
    as the only digraph); it overrides the three mode flags. No compiler
    reads a file that way, but it is scanned too so that nothing the old
    scanner refused is accepted now.
    ``separators`` picks how a ``'`` right after a pp-number is lexed (a
    wrong guess lets a character literal swallow a quote or a ``/*`` and
    hide later lines): ``"cxx14"`` (C++14, C23: a digit separator when an
    ASCII digit, letter or ``_`` follows, as gcc and clang read it; where
    MSVC reads it otherwise the input is refused, see ``_mask_literals``),
    ``"none"`` (C17, C++11: always a character literal) and ``"legacy"``
    (the masking before these modes: any ``'`` inside a pp-number, whose
    start was any Unicode digit). See ``_mask_literals``.
    """
    value = _translation_phases(text, trigraphs=trigraphs, digraphs=digraphs,
                                strict_splices=strict_splices, legacy=legacy)
    return _mask_literals(value, raw_strings=raw_strings, digraphs=digraphs and not legacy,
                          separators=separators)


def _translation_phases(text: str, *, trigraphs: bool = True, digraphs: bool = True,
                        strict_splices: bool = False, legacy: bool = False) -> str:
    """The whole-text part of ``normalize_for_scan``: line ends, trigraphs, splices, ``%:``."""
    value = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    if legacy:
        value = value.replace("??=", "#").replace("??/", "\\")
        value = _LEGACY_SPLICE_RE.sub("", value)
        value = value.replace("%:%:", "##").replace("%:", "#")
    else:
        if trigraphs:
            value = _TRIGRAPH_RE.sub(lambda m: _TRIGRAPHS[m.group(1)], value)
        value = value.replace(_STRICT_SPLICE, "") if strict_splices \
            else _SPLICE_RE.sub("", value)
        if digraphs:
            value = value.replace("%:%:", "##").replace("%:", "#")
    return value


# Characters the masking loop only copies: ASCII that cannot start a comment,
# a literal, a raw-string prefix, a pp-number or a digraph. Runs of them are
# copied in one step.
_PLAIN_RUN_RE = re.compile(r"(?:[^/\"'<:%0-9.uULR\x80-\U0010ffff]|u(?!8?R\")|[UL](?!R\")|R(?!\"))+")
_LETTERS_RE = re.compile(r"[A-Za-z_]+")
_MASK_STARTERS = "/\"'<:%0123456789."  # never plain: skip the run match for these
_ASCII_DIGITS = frozenset("0123456789")
_ASCII_IDENT = frozenset("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_")
_ASCII_IDENT_RUN_RE = re.compile(r"[A-Za-z0-9_]+")
_IDENT_OR_DOLLAR = _ASCII_IDENT | {"$"}
_UNSURE_IN_NUMBER = frozenset("\\$")  # a UCN or ``$``: gcc continues a pp-number over it
_EXPONENTS = frozenset("eEpP")
_SIGNS = frozenset("+-")
_HEX_DIGITS = frozenset("0123456789abcdefABCDEF")
# The literal part of a pp-number as MSVC 19.44 lexes it: digits with separators, a fraction, an
# exponent, then an optional trailing ``'``. MSVC reads a ``'`` as a separator only right after a
# digit of this part, and its number token ends where the part ends (``1x.R"(`` is ``1x``, ``.``
# and a raw string to it), while gcc and clang continue the pp-number over every identifier
# character, ``.``, ``'`` and exponent sign. Matched once per number, only when needed.
_DEC_RUN = r"[0-9](?:'?[0-9])*"
_HEX_RUN = r"[0-9A-Fa-f](?:'?[0-9A-Fa-f])*"
_LITERAL_PART_RE = re.compile(
    rf"(?:0[xX](?:{_HEX_RUN})?(?:\.(?:{_HEX_RUN})?)?(?:[pP][+-]?(?:{_DEC_RUN})?)?"
    rf"|0[bB](?:{_DEC_RUN})?"
    rf"|(?:{_DEC_RUN}(?:\.(?:{_DEC_RUN})?)?|\.{_DEC_RUN})(?:[eE][+-]?(?:{_DEC_RUN})?)?)'?")


def _literal_part_end(value: str, start: int) -> int:
    """End of the literal part of the number starting at ``start`` (see ``_LITERAL_PART_RE``)."""
    match = _LITERAL_PART_RE.match(value, start)
    return start if match is None else match.end()


_SEPARATOR_MODES = ("cxx14", "none", "legacy")
# What one ``_mask_literals`` pass saw (``events``); ``scan_added_lexings`` acts on them.
_EVENT_SEPARATOR = "separator"  # a ``'`` the C++14 reading took as a digit separator
_EVENT_LEGACY = "legacy"        # the legacy masking lexes a ``'`` or a raw prefix differently
_EVENT_AMBIGUOUS = "ambiguous"  # a ``'`` after a pp-number that compilers lex differently
_EVENT_BAD_RAW = "bad_raw"      # a raw-string prefix whose delimiter some compiler rejects
_AMBIGUOUS_SEPARATOR = ("a quote after a number that compilers lex differently (digit separator "
                        "or character literal) is refused")
_BAD_RAW_DELIMITER = ("a raw string prefix that compilers lex differently (a delimiter some compiler "
                      "rejects, or a prefix inside a number) is refused")


def _mask_literals(value: str, *, raw_strings: bool, digraphs: bool, separators: str = "cxx14",
                   events: set[str] | None = None) -> str:
    """The token-level part of ``normalize_for_scan``: comments, raw strings, digraph pairs.

    A ``'`` right after a pp-number is where compilers part ways. Checked with
    gcc 16, clang 22 and MSVC 19.44: in C++14 and C23 modes gcc and clang take
    it as a digit separator only when an ASCII digit, letter or ``_`` follows
    (gcc also across ``''``), in C17 and C++11 never, and MSVC in every mode
    exactly when it follows a digit of the number's literal part
    (``_LITERAL_PART_RE``: ``1'/`` yes, ``1x'2``, ``1.'2``, ``1e+'2`` no).
    The exponent sign is not uniform either: clang (C++) and g++
    ``-std=c++14`` end the number before a sign after ``p`` in a decimal
    number (g++ C++11 and C++14 in a hex one too: ``0xp+``, ``0x.p-``),
    clang in MS mode before a sign after ``e`` in a hex one.
    ``separators`` picks the reading (see
    ``normalize_for_scan``); every reading follows the same text up to the
    first ``'`` it decides differently, so ``events`` (when given) records
    whether another reading can differ at all: ``"separator"`` (the C++14
    reading took a separator, so the C17 one differs), ``"legacy"`` (the
    legacy reading decides a ``'`` or a raw prefix differently) and the two
    that no reading covers: ``"ambiguous"`` (a ``'`` after a pp-number
    followed by anything else, one gcc and clang take as a separator but
    MSVC does not, one after a sign after ``p`` or in a hex number, or a
    pp-number holding a character compilers disagree on: non-ASCII, ``\\``,
    ``$``; taken from the C++14 pass) and ``"bad_raw"`` (a raw prefix whose
    delimiter some compiler rejects, one after a non-ASCII character or a
    backslash, or one inside a pp-number that some compiler ends before it).
    A raw prefix inside a pp-number every compiler continues (``1.R"(``,
    ``1'R"(``, ``1e+R"(``) is no raw string: ``1.R`` is part of the number.

    Pure; ``events`` is the only argument it mutates. Linear in ``value``.
    """
    if separators not in _SEPARATOR_MODES:
        raise ValueError(f"separators must be one of {', '.join(_SEPARATOR_MODES)}")
    out: list[str] = []
    i = 0
    n = len(value)
    pp_number = False  # C++14 reading: inside a pp-number (started by an ASCII digit)
    unsure = False  # ... and it holds a character compilers lex differently
    number_start = 0  # ... where it starts
    hex_number = False  # ... and whether it starts with ``0x``
    literal_end = -1  # ... end of its literal part (``_LITERAL_PART_RE``), -1 until needed
    legacy_pp = False  # the legacy tracker: started by any Unicode digit, ' always continues it
    while i < n:
        ch = value[i]
        if pp_number or legacy_pp:
            # Inside a number: ASCII identifier characters after one continue it in every
            # tracker (and cannot start one or a raw prefix), so copy them in one step.
            if ch in _ASCII_IDENT and i > 0 and value[i - 1] in _ASCII_IDENT:
                j = _ASCII_IDENT_RUN_RE.match(value, i).end()
                out.append(value[i:j])
                i = j
                continue
        elif ch not in _MASK_STARTERS:
            run = _PLAIN_RUN_RE.match(value, i)
            if run is not None:
                j = run.end()
                out.append(value[i:j])
                i = j
                continue
        if ch == "'" and (pp_number or legacy_pp):
            separator = pp_number and not unsure and value[i + 1:i + 2] in _ASCII_IDENT
            if events is not None:
                if pp_number and not separator:
                    events.add(_EVENT_AMBIGUOUS)
                elif separator and separators == "cxx14":
                    # MSVC takes it only after a digit of the literal part. Matched in the C++14
                    # pass alone (where a number's literal part does not run into the next number).
                    if literal_end < 0:
                        literal_end = _literal_part_end(value, number_start)
                    if i - 1 >= literal_end \
                            or value[i - 1] not in (_HEX_DIGITS if hex_number else _ASCII_DIGITS):
                        events.add(_EVENT_AMBIGUOUS)
                if separator:
                    events.add(_EVENT_SEPARATOR)
                if separator != legacy_pp:
                    events.add(_EVENT_LEGACY)
            take = legacy_pp if separators == "legacy" else separator and separators == "cxx14"
            if take:
                out.append(ch)
                i += 1
                continue
        previous = value[i - 1] if i > 0 else ""
        if legacy_pp:
            legacy_pp = ch.isalnum() or ch in "_."
        elif not (previous.isalnum() or previous == "_") and (
                ch.isdigit() or (ch == "." and i + 1 < n and value[i + 1].isdigit())):
            legacy_pp = True
        if pp_number:
            if ch in _ASCII_IDENT or ch == ".":
                pass
            elif ch in _SIGNS and previous in _EXPONENTS:
                # gcc and clang disagree whether the number goes on after ``p+`` or a hex ``e+``.
                if previous in "pP" or hex_number:
                    unsure = True
            elif ch in _UNSURE_IN_NUMBER or not ch.isascii():
                unsure = True
            else:
                pp_number = unsure = False
        elif (ch in _ASCII_DIGITS and previous not in _ASCII_IDENT) \
                or (ch == "." and value[i + 1:i + 2] in _ASCII_DIGITS):
            # "." is never an identifier character, so ``.`` plus a digit starts a pp-number
            # even right after one: ``b.0x1`` is ``b`` and ``.0x1``, literal part ``.0``.
            # ASCII digits only: a Unicode digit (U+0661, U+FF11, U+00B2) is an identifier
            # character to the compilers. After a non-ASCII character, ``\`` or ``$`` it is
            # unsure whether the digit starts a number or continues an identifier.
            pp_number = True
            unsure = previous != "" and (previous in _UNSURE_IN_NUMBER or not previous.isascii())
            number_start = i
            hex_number = value.startswith(("0x", "0X"), i)
            literal_end = -1
        if ch == "/" and i + 1 < n and value[i + 1] == "/":
            end = value.find("\n", i)
            out.append(" ")
            i = n if end < 0 else end
            continue
        if ch == "/" and i + 1 < n and value[i + 1] == "*":
            end = value.find("*/", i + 2)
            out.append(" ")
            i = n if end < 0 else end + 2
            continue
        if raw_strings and ch in "uULR" and _RAW_OPEN_RE.match(value, i) is not None:
            legacy_raw = None if previous.isalnum() or previous == "_" \
                else _LEGACY_RAW_PREFIX_RE.match(value, i)
            if previous in _IDENT_OR_DOLLAR:
                raw = None  # ``xR"`` and ``$R"`` are identifiers to every compiler
            elif pp_number:
                # ``1.R"(``, ``1'R"(``, ``1e+R"(``: the prefix continues the number. Unless some
                # compiler ends the number before it (an unsure number, or past MSVC's literal
                # part); a delimiter some compiler rejects stays refused here too, as before.
                raw = None
                if events is not None:
                    if literal_end < 0:
                        literal_end = _literal_part_end(value, number_start)
                    if unsure or i - 1 >= literal_end or _RAW_PREFIX_RE.match(value, i) is None:
                        events.add(_EVENT_BAD_RAW)
            else:
                raw = _RAW_PREFIX_RE.match(value, i)
                # After a non-ASCII character or a stray backslash it is unsure whether an
                # identifier continues (no raw string) or a blank precedes one.
                if events is not None and (raw is None or previous == "\\"
                                           or not previous.isascii()):
                    events.add(_EVENT_BAD_RAW)
            if events is not None and (raw is None) != (legacy_raw is None):
                events.add(_EVENT_LEGACY)
            if separators == "legacy":
                raw = legacy_raw
            if raw:
                delimiter = ")" + raw.group(1) + '"'
                start = raw.end()
                end = value.find(delimiter, start)
                end = n if end < 0 else end
                body = value[start:end]
                out.append(value[i:start])
                out.append("".join("\n" if c == "\n" else "x" for c in body))
                out.append(delimiter if end < n else "")
                i = end + len(delimiter) if end < n else n
                continue
        if ch in "\"'":
            quote = ch
            j = i + 1
            while j < n and value[j] != quote and value[j] != "\n":
                j += 2 if value[j] == "\\" else 1
            out.append(value[i:min(j + 1, n)])
            i = j + 1
            continue
        if digraphs and ch in "<:%" and i + 1 < n:
            pair = value[i:i + 2]
            if pair == "<:":
                if value[i + 2:i + 3] == ":" and value[i + 3:i + 4] not in (":", ">"):
                    out.append("<")  # ``<::`` is ``<`` ``::`` (std::vector<::T>), not a digraph
                    i += 1
                else:
                    out.append("[")
                    i += 2
                continue
            if pair == "<%":
                out.append("{")
                i += 2
                continue
            if pair == "%>":
                out.append("}")
                i += 2
                continue
            if pair == ":>":
                out.append("]")
                i += 2
                continue
            if pair == "::":
                out.append("::")  # maximal munch: ``::`` is one token, so ``::>`` is not ``:>``
                i += 2
                continue
        out.append(ch)
        i += 1
    return "".join(out)


# ``\s`` is wider than any compiler's blank (it takes U+00A0, U+2028, U+0085,
# \x1c-\x1f, which gcc lexes as stray tokens), so this recognises more lines
# as directives, never fewer, and checks them. What it misses (U+180E, which
# clang treats as blank but ``\s`` does not) is refused by the check below.
_DIRECTIVE_RE = re.compile(r"^\s*#\s*([A-Za-z_]\w*)\s*(.*)$")
# A line that starts like a directive: what precedes the ``#`` (group 1), what
# separates it from the name (group 2), the ASCII name (3) and the next character (4).
_DIRECTIVE_SHAPE_RE = re.compile(r"([^\x21-\x7e]*)(?:#|%:)([^\x21-\x7e]*)([A-Za-z0-9_]*)(.?)")
_LINE_BLANKS = frozenset(" \t\f\v\r")
_ODD_DIRECTIVE = ("a non-ASCII or control character before, after or inside a directive's '#' "
                  "and name is refused (compilers disagree whether the line is a directive)")
# U+FEFF is skipped as a byte order mark at the start of a file by gcc, clang and MSVC;
# clang 22 takes U+180E as a blank before a ``#`` (not between ``_Pragma`` and its
# ``(``). ``\s`` matches neither; both are refused anywhere in added text, one
# rule instead of a guess per construct (``scan_added_lexings`` drops the one
# byte order mark at offset 0 of a file before scanning).
_ODD_BLANKS_RE = re.compile("[\ufeff\u180e]")
_ODD_BLANKS = "U+FEFF (byte order mark) or U+180E in added text is refused (a compiler reads it as a blank)"
_PRAGMA_BAD_RE = re.compile(
    r"\b(?:comment\s*\(\s*(?:linker|lib|user)\b|include_alias|section|init_seg|code_seg|"
    r"data_seg|const_seg|bss_seg|alloc_text|detect_mismatch)\b|\bGCC\s+poison\b|"
    r"\bclang\s+(?:section|attribute)\b",
    re.IGNORECASE,
)
_PRAGMA_OP_RE = re.compile(r"\b_Pragma\s*\(")
_MS_PRAGMA_RE = re.compile(r"\b__pragma\s*\(")
# ``__has_include__``/``__has_include_next__`` are the spellings older GCC used.
_HAS_TOKEN_RE = re.compile(r"\b__has_(?:include(?:_next)?(?:__)?|embed)\b")
# ``(`` then ``<`` or ``"``. A use needs the whole operand on the token's own
# logical line; the match may run past it because a literal that follows a
# merely named token on a later line is still path-checked.
_HAS_OPERAND_RE = re.compile(r"\s*\(\s*([<\"])")
# Directives whose first operand is a macro *name*: there the token is defined,
# removed or tested, never evaluated. Matched from the start of the logical
# line, so text before the ``#`` (``#if 0 #define __has_include(P)``, a
# stringized or pasted ``#define``) is not a directive head.
# Both grant an exemption, so they take only the blanks every compiler skips
# (``\s`` would also take U+00A0 or \x1c, a stray token to gcc, which then
# expands ``__has_include(P)`` on that line as ordinary text), and ``if``/``elif``
# must not run on into an identifier character, ASCII or not.
_HAS_NAME_HEAD_RE = re.compile(
    r"[ \t\f\v]*(?:#|%:)[ \t\f\v]*(?:define|undef|ifdef|ifndef|elifdef|elifndef)[ \t\f\v]+")
_HAS_IF_HEAD_RE = re.compile(r"[ \t\f\v]*(?:#|%:)[ \t\f\v]*(?:if|elif)(?![0-9A-Za-z_$]|[^\x00-\x7f])")
# Words of an ``#if`` line. Group 1 is anything that may be (or hide) a macro:
# an identifier, or a quote, backslash or other character that starts a token
# this scan does not pair up. A pp-number and ``defined NAME``/``defined(NAME``
# (its operand is never expanded) are not.
# ASCII digits only: Python's \d also matches Unicode Nd (U+0663, U+FF11), which C
# compilers accept as identifier characters, so "\uff11LP" must be an identifier here.
_IF_WORD_RE = re.compile(r"\.?[0-9](?:[eEpP][+-]|'?[\w.])*|defined\b[ \t\f\v]*\(?[ \t\f\v]*(?:[^\W0-9]\w*)?"
                         r"|([^\W0-9]\w*|[$\\'\"`@]|[^\x00-\x7f])")
_HAS_COMPUTED = "__has_include/__has_embed: computed operand (not a literal header-name)"
_HEADER_NAME_LIMIT = 4096
# Budget steps per token: its path check costs about what 500 plain characters do.
_HAS_TOKEN_STEPS = 512
_BLANKS = " \t\f\v"
_ASM_RE = re.compile(r"\b(?:asm|__asm__|__asm)\b")
# An assembler directive anywhere in added code: in an asm body, a string
# literal, a macro that later feeds asm (``#define X .incbin "f"``) or a
# stringized argument (``asm(S(.incbin "f"))``). gas directives are
# case-insensitive. A member access (``cfg.file``) is preceded by an
# identifier character, ``)`` or ``]`` and does not match.
_ASM_DIRECTIVE_RE = re.compile(r"(?:^|[^\w)\].])\.(?:incbin|include|file|section|pushsection|"
                               r"init_array|fini_array|ctors|dtors)\b", re.IGNORECASE)
_ATTRIBUTE_RE = re.compile(r"\b__attribute(?:__)?\s*\(\s*\(")
_ATTR_BAD_RE = re.compile(r"\b_{0,2}(?:section|constructor|destructor|ifunc|alias|weakref|"
                          r"init_priority)_{0,2}\b")
# Every ``[[...]]`` body is checked, so ``[[__gnu__::constructor]]`` and
# ``[[using gnu: constructor]]`` are caught like ``[[gnu::constructor]]``.
_CXX_ATTR_OPEN_RE = re.compile(r"\[\s*\[")
_STRING_RUN_RE = re.compile(r'"(?:[^"\\\n]|\\.)*"(?:\s*"(?:[^"\\\n]|\\.)*")+')
# Suffixless ``<...>`` includes stay allowed (``<vector>``) except names
# that are dotfiles or credentials reachable through an ``-I`` directory.
_SECRET_INCLUDE_NAMES = frozenset({
    "id_rsa", "id_dsa", "id_ecdsa", "id_ed25519", "credentials", "secrets", "passwd", "shadow",
    "authorized_keys", "known_hosts",
})
_DECLSPEC_RE = re.compile(r"\b__declspec\s*\(\s*(?:allocate|code_seg)\b")
_STRING_RE = re.compile(r'"(?:[^"\\\n]|\\.)*"')


class _ScanBudgetExceeded(Exception):
    """The scan did more work than a bounded input can legitimately need."""


class _Budget:
    """Character-steps still allowed for one scan (shared by every bounded sub-scan)."""

    __slots__ = ("left",)

    def __init__(self, steps: int) -> None:
        self.left = steps

    def charge(self, steps: int) -> None:
        self.left -= steps
        if self.left < 0:
            raise _ScanBudgetExceeded


# Each unterminated opener re-scans up to 4096 characters, so N openers cost
# N * 4096 steps. A scan may spend this base plus a few steps per input
# character; past it the input is refused (fail closed), never accepted.
_SCAN_BUDGET_BASE = 262_144
_SCAN_BUDGET_PER_CHAR = 8


def _balanced(text: str, start: int, limit: int = 4096, budget: _Budget | None = None) -> str:
    """Text from ``start`` (just after an opening paren) to its closing paren."""
    depth = 1
    i = start
    end = min(len(text), start + limit)
    quote = ""
    while i < end:
        ch = text[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                if budget is not None:
                    budget.charge(2 * (i - start) + 1)
                return text[start:i]
        i += 1
    if budget is not None:
        budget.charge(2 * (end - start) + 1)
    return text[start:end]


_C_ESCAPE_RE = re.compile(
    r"\\(?:x([0-9A-Fa-f]+)|([0-7]{1,3})|u([0-9A-Fa-f]{4})|U([0-9A-Fa-f]{8})|([ntrabfv'\"\\?]))")
_C_SIMPLE_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "a": "\a", "b": "\b", "f": "\f", "v": "\v",
                     "'": "'", '"': '"', "\\": "\\", "?": "?"}


def _decode_escape(match: re.Match) -> str:
    hex_digits, octal, small, large, simple = match.groups()
    if simple is not None:
        return _C_SIMPLE_ESCAPES[simple]
    if hex_digits is not None:
        return chr(int(hex_digits, 16) & 0xFF)  # greedy like C; the byte is what reaches the assembler
    if octal is not None:
        return chr(int(octal, 8) & 0xFF)
    code = int(small if small is not None else large, 16)
    return chr(code) if code <= 0x10FFFF else match.group(0)


def _unescape(literal: str) -> str:
    """Decode the C escapes (simple, octal, ``\\x``, ``\\u``, ``\\U``) of a string literal.

    ``.\\x69ncbin`` and ``.\\151ncbin`` reach the assembler as ``.incbin``, so the
    directive scan has to see the decoded text.
    """
    body = literal[1:-1] if len(literal) >= 2 else literal
    return _C_ESCAPE_RE.sub(_decode_escape, body)


def include_path_problem(path: str, *, quoted: bool) -> str:
    """Why an include path is refused ('' when acceptable), before containment."""
    if not path or "\x00" in path:
        return "empty include path"
    text = path.replace("\\", "/")
    if text.startswith("/") or re.match(r"^[A-Za-z]:", text) or text.startswith("//"):
        return "absolute include path"
    suffix = posixpath.splitext(posixpath.basename(text))[1].lower()
    if suffix:
        if suffix not in INCLUDE_SUFFIXES:
            return "include of a non-header file"
    elif quoted:
        return "quoted include without a header suffix"
    if not quoted and ".." in text.split("/"):
        return "system include escaping upward"
    base = posixpath.basename(text).lower()
    if base.startswith(".") or base in _SECRET_INCLUDE_NAMES \
            or base in {name.lower() for name in DENIED_NAMES}:
        return "include of a dotfile or credential file"
    return ""


def _include_target(rest: str) -> tuple[str, bool] | None:
    rest = rest.strip()
    if rest.startswith('"'):
        end = rest.find('"', 1)
        return (rest[1:end], True) if end > 0 else None
    if rest.startswith("<"):
        end = rest.find(">", 1)
        return (rest[1:end], False) if end > 0 else None
    return None


def _is_defined_operand(text: str, line_start: int, start: int, end: int, line_end: int,
                        budget: _Budget) -> bool:
    """``defined(TOKEN)`` or ``defined TOKEN`` (the token is tested, not evaluated)."""
    j = start
    while j > line_start and text[j - 1] in _BLANKS:
        j -= 1
    paren = j > line_start and text[j - 1] == "("
    if paren:
        j -= 1
        while j > line_start and text[j - 1] in _BLANKS:
            j -= 1
    k = end
    while k < line_end and text[k] in _BLANKS:
        k += 1
    budget.charge(start - j + k - end + 1)
    if j - 7 < line_start or text[j - 7:j] != "defined":
        return False
    # Any non-ASCII character may continue an identifier (U+0300, U+00B7, ZWJ,
    # U+203F are not ``isalnum`` but compilers accept them), so ``X\u0300defined``
    # is one identifier, not the operator.
    if j - 7 > line_start and (text[j - 8] in _IDENT_OR_DOLLAR or not text[j - 8].isascii()):
        return False
    following = text[k] if k < line_end else ""
    return following == ")" if paren else following != "("


def _scan_has_include(text: str, *, include_ok: Callable[[str], bool], budget: _Budget,
                      refuse: Callable[[str], None]) -> None:
    """Check every ``__has_include``-family token spelled in ``text``.

    The compiler probes the file system for the operand, so a use is accepted
    only with a literal header-name that passes the include rules. A token
    not directly followed by ``(`` and ``<`` or ``"`` on its own logical line
    is refused: ``__has_include(P)``, a bare token (``#define H __has_include``
    makes an alias) and a parenthesis that comes from a macro all lead to a
    computed path.

    Not a use: the macro name of ``#define``/``#undef``/``#ifdef``/``#ifndef``
    when that directive starts the logical line (the fallback shim
    ``#define __has_include(x) 0``), and ``defined(__has_include)``/``defined
    __has_include`` in ``#if``/``#elif``. Wherever the token stands, a literal
    operand that follows it (even on a later line) still has to pass the
    include rules.

    A ``<...>`` operand is a header-name only where the compiler lexes it as
    one: written directly in an ``#if``/``#elif`` line. In a macro body or a
    macro argument its tokens are macro-expanded first (clang and MSVC both
    do this), and any identifier earlier on the line may expand to the call
    that makes it an argument (``#define LP F(``). So on an ``#if``/``#elif``
    line a ``<...>`` operand is refused once anything but ``defined NAME``,
    numbers, operators and other checked ``__has_include`` operands precedes
    it. A quoted operand is a string literal and is never expanded.

    What this cannot see (pinned by the ``test_gap_*`` tests): a token built
    by ``##`` pasting, and an alias macro defined in code the patch does not
    touch.

    Each logical line is located once and its directive head matched once;
    every per-token walk is charged, so the work stays linear, and each token
    is charged ``_HAS_TOKEN_STEPS`` for its path check, so a file that is
    mostly probe tokens exhausts the budget and is refused.
    """
    line_start = 0
    line_end = -1
    name_at = -1
    in_if = False
    walked = 0  # #if/#elif lines: the line is checked for identifiers up to here
    opened = True  # ... and one was seen (or the line is not #if/#elif at all)
    size = len(text)
    for match in _HAS_TOKEN_RE.finditer(text):
        budget.charge(_HAS_TOKEN_STEPS)
        start, end = match.span()
        if start > line_end:  # first token of the next logical line
            line_start = text.rfind("\n", max(line_end, 0), start) + 1
            line_end = text.find("\n", end)
            if line_end < 0:
                line_end = size
            head = _HAS_NAME_HEAD_RE.match(text, line_start, line_end)
            name_at = head.end() if head else -1
            head = _HAS_IF_HEAD_RE.match(text, line_start, line_end)
            in_if = head is not None
            walked = head.end() if head else line_end
            opened = not in_if
        if not opened and start > walked:
            budget.charge(start - walked)
            opened = any(word.lastindex == 1 for word in _IF_WORD_RE.finditer(text, walked, start))
        walked = max(walked, end)
        operand = _HAS_OPERAND_RE.match(text, end)
        problem = ""
        close = -1
        quoted = False
        if operand is not None:
            quoted = operand.group(1) == '"'
            name_start = operand.end()
            limit = min(size, name_start + _HEADER_NAME_LIMIT)
            close = text.find('"' if quoted else ">", name_start, limit)
            budget.charge((limit if close < 0 else close) - name_start + 1)
            path = text[name_start:close] if close > name_start else ""
            problem = include_path_problem(path, quoted=quoted) if path else "computed __has_include"
            if not problem and quoted and not include_ok(path):
                problem = "include escapes the project root"
        if start == name_at or (in_if and _is_defined_operand(text, line_start, start, end,
                                                             line_end, budget)):
            # Named, not evaluated; a literal after it is still checked as before.
            if problem:
                refuse("__has_include/__has_embed: " + problem)
            continue
        if operand is None or not 0 <= close < line_end:
            refuse(_HAS_COMPUTED)
            continue
        if not problem and not quoted and opened:
            problem = ("<...> operand outside a plain #if/#elif (macro-expanded, so computed); "
                           "test it alone in a nested #if")
        walked = max(walked, close + 1)
        if problem:
            refuse("__has_include/__has_embed: " + problem)


def scan_hostile_directives(added_text: str, *,
                            include_ok: Callable[[str], bool]) -> tuple[str, ...]:
    """Reasons the added (already normalized) logical lines are refused.

    ``include_ok(path)`` decides containment of a quoted include relative to
    the edited file (it must refuse ``..`` escaping the project root).
    Each ``__has_include``/``__has_include_next``/``__has_embed`` token spelled
    in the text is refused unless its operand is a checkable literal
    header-name (see ``_scan_has_include`` for what that cannot see).
    Every opener scan (``_Pragma(``, ``__pragma(``, ``__attribute__((``, ``asm``,
    ``[[``, ``__has_include``) charges the characters it walks to a budget of
    a fixed base plus 8 steps per input character, and each walk is capped
    (4096 characters, 1026 for ``[[``), so the total work is linear in the
    input. An input that exhausts the budget (thousands of unterminated
    openers) is refused, never accepted.
    """
    text = str(added_text or "")
    budget = _Budget(_SCAN_BUDGET_BASE + _SCAN_BUDGET_PER_CHAR * len(text))
    try:
        return _scan_hostile_directives(text, include_ok=include_ok, budget=budget)
    except _ScanBudgetExceeded:
        return ("scan work budget exceeded (unterminated openers); the input is refused",)


def _scan_hostile_directives(text: str, *, include_ok: Callable[[str], bool],
                             budget: _Budget) -> tuple[str, ...]:
    reasons: list[str] = []

    def refuse(reason: str) -> None:
        if reason not in reasons:
            reasons.append(reason)

    if _ODD_BLANKS_RE.search(text):
        refuse(_ODD_BLANKS)
    for line in text.split("\n"):
        shape = _DIRECTIVE_SHAPE_RE.match(line)
        if shape is not None:
            lead, gap, name, after = shape.groups()
            if any(c not in _LINE_BLANKS for c in lead) or any(c not in _LINE_BLANKS for c in gap) \
                    or (name and after and after not in _LINE_BLANKS
                        and not "\x21" <= after <= "\x7e"):
                refuse(_ODD_DIRECTIVE)
        directive = _DIRECTIVE_RE.match(line)
        if not directive:
            continue
        name, rest = directive.group(1), directive.group(2)
        if name in ("include", "include_next", "import"):
            if name == "import":
                refuse("#import is refused")
                continue
            target = _include_target(rest)
            if target is None:
                refuse("computed #include is refused")
                continue
            path, quoted = target
            problem = include_path_problem(path, quoted=quoted)
            if problem:
                refuse(problem)
            elif quoted and not include_ok(path):
                refuse("include escapes the project root")
        elif name == "using":
            refuse("#using is refused")
        elif name == "embed":
            refuse("#embed is refused")
        elif name == "line":
            refuse("#line is refused (it redirects later diagnostics)")
        elif name == "pragma":
            if _PRAGMA_BAD_RE.search(rest):
                refuse("#pragma %s is refused" % clip(rest.split("(")[0].strip(), 40))
    for match in _PRAGMA_OP_RE.finditer(text):
        body = _balanced(text, match.end(), budget=budget)
        literals = _STRING_RE.findall(body)
        if not literals:
            refuse("_Pragma without a string literal is refused")
            continue
        if _PRAGMA_BAD_RE.search(" ".join(_unescape(item) for item in literals)):
            refuse("_Pragma with a linker/section directive is refused")
    for match in _MS_PRAGMA_RE.finditer(text):
        if _PRAGMA_BAD_RE.search(_balanced(text, match.end(), budget=budget)):
            refuse("__pragma with a linker/section directive is refused")
    _scan_has_include(text, include_ok=include_ok, budget=budget, refuse=refuse)

    def _asm_text(chunk: str) -> str:
        return chunk.replace("\\n", "\n").replace("\\t", " ")

    for match in _ASM_RE.finditer(text):
        window = text[match.end(): match.end() + 4096]
        paren = window.find("(")
        brace = window.find("{")
        if paren >= 0 and (brace < 0 or paren < brace):
            body = _balanced(window, paren + 1, budget=budget)
        elif brace >= 0:
            end = window.find("}", brace)
            body = window[brace: end if end > 0 else len(window)]
        else:
            body = window[:256]
        budget.charge(4 * len(body) + 1)  # the string/regex passes below walk the whole body
        joined = "".join(_unescape(item) for item in _STRING_RE.findall(body))
        if _ASM_DIRECTIVE_RE.search(_asm_text(body)) or _ASM_DIRECTIVE_RE.search(_asm_text(joined)):
            refuse("inline assembly with an assembler file/section directive is refused")
    if _ASM_DIRECTIVE_RE.search(_STRING_RE.sub(" ", text)):
        refuse("assembler file/section directive in code or a macro is refused")
    literals = [_unescape(item) for item in _STRING_RE.findall(text)]
    # Adjacent literals concatenate (".inc" "bin"): each run is also one string.
    literals.extend("".join(_unescape(item) for item in _STRING_RE.findall(run))
                    for run in _STRING_RUN_RE.findall(text))
    for literal in literals:
        if _ASM_DIRECTIVE_RE.search(_asm_text(literal)):
            refuse("string literal carrying an assembler directive is refused")
            break
    for match in _ATTRIBUTE_RE.finditer(text):
        if _ATTR_BAD_RE.search(_balanced(text, match.end(), budget=budget)):
            refuse("__attribute__ section/constructor/destructor is refused")
    for match in _CXX_ATTR_OPEN_RE.finditer(text):
        window_end = min(len(text), match.end() + 1026)
        end = text.find("]]", match.end(), window_end)
        stop = window_end if end < 0 else end
        budget.charge(stop - match.end() + 1)
        body = text[match.end(): min(stop, match.end() + 1024)]
        if _ATTR_BAD_RE.search(body):
            refuse("[[gnu::section/constructor/destructor]] is refused")
            break
    if _DECLSPEC_RE.search(text):
        refuse("__declspec(allocate/code_seg) is refused")
    growth = sum(len(item) - 2 for item in _STRING_RE.findall(text))
    if growth > MAX_STRING_GROWTH:
        refuse("string literal growth above 64 KiB is refused")
    return tuple(reasons)


def added_logical_lines(before: str, after: str, *, raw_strings: bool = True,
                        trigraphs: bool = True, digraphs: bool = True,
                        strict_splices: bool = False, legacy: bool = False,
                        separators: str = "cxx14") -> str:
    """Normalized logical lines present in ``after`` but not in ``before`` (multiset)."""
    return _added_lines(
        normalize_for_scan(before, raw_strings=raw_strings, trigraphs=trigraphs,
                           digraphs=digraphs, strict_splices=strict_splices, legacy=legacy,
                           separators=separators),
        normalize_for_scan(after, raw_strings=raw_strings, trigraphs=trigraphs,
                           digraphs=digraphs, strict_splices=strict_splices, legacy=legacy,
                           separators=separators))


def _added_lines(old_text: str, new_text: str) -> str:
    """Lines of ``new_text`` that ``old_text`` does not have (multiset difference, order kept)."""
    counts: dict[str, int] = {}
    for line in old_text.split("\n"):
        counts[line] = counts.get(line, 0) + 1
    added: list[str] = []
    for line in new_text.split("\n"):
        if counts.get(line, 0) > 0:
            counts[line] -= 1
        else:
            added.append(line)
    return "\n".join(added)


def _may_hold_digraph(text: str) -> bool:
    """True when a digraph could appear once splices (and trigraphs) are applied.

    Any of the five spellings counts: read as written, ``<:``/``<%`` open a
    header-name, and ``:>``/``%>``/``%:`` are operator characters that the
    digraph reading turns into ``]``/``}``/``#``.
    """
    value = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    for candidate in (value, _TRIGRAPH_RE.sub(lambda m: _TRIGRAPHS[m.group(1)], value)):
        joined = _SPLICE_RE.sub("", candidate)
        if any(pair in joined for pair in _DIGRAPH_PAIRS):
            return True
    return False


def _blank_splices(text: str) -> tuple[bool, bool]:
    """(a backslash-blanks-newline exists, one of them holds a form feed or vertical tab)."""
    value = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    found = False
    for match in _BLANK_SPLICE_RE.finditer(value):
        found = True
        if "\f" in match.group(1) or "\v" in match.group(1):
            return True, True
    return found, False


# Characters (old text plus new text, once per distinct reading) that one
# ``scan_added_lexings`` call may normalise and scan. Two readings are always
# allowed; a file that needs more and would pass this total is refused instead
# of costing seconds per patch. All 18 readings fit while old plus new text
# total about 166 kB; 3 readings fit up to 1 MB.
_LEXING_WORK_CHARS = 3_000_000
_LOOP_DIGRAPHS = ("<:", ":>", "<%", "%>")
_LEXING_REFUSAL = ("too many distinct readings for a file this large "
                   "(lexing work budget exceeded); the input is refused")


def _without_bom(text: str) -> str:
    """``text`` without one U+FEFF at offset 0 (the byte order mark every compiler skips)."""
    return str(text or "").removeprefix("\ufeff")


def _digest(text: str) -> bytes:
    return hashlib.blake2b(text.encode("utf-8", "surrogatepass"), digest_size=16).digest()


def scan_added_lexings(before: str, after: str, *,
                       include_ok: Callable[[str], bool]) -> tuple[str, ...]:
    """Union of the hostile-scan reasons over every lexing a compiler might use.

    The lexings that change what the scanner sees: C++ raw strings versus C
    (``R"(`` is an identifier and a string), trigraphs applied (``-trigraphs``,
    ``-std=c++14``) versus ignored (the gcc/clang/MSVC default), digraphs
    normalised versus left as written (a header-name such as ``<:/../x.h>``
    is never digraph-translated by the compiler), and a backslash-blanks-newline
    spliced (gcc, clang) versus left alone (MSVC). The legacy reading (see
    ``normalize_for_scan``) is scanned as well, so nothing it refused is
    accepted now.

    That is up to 18 readings, but most of them read a given file the same
    way. A reading is skipped when its whole-text phases give the same old
    and new text as one already done (and the raw-string and digraph-pair
    switches cannot matter because the text has no ``R"`` or digraph pair),
    and its added lines are scanned only when no earlier reading produced the
    same ones. Ordinary code costs one normalisation and one scan.

    Each of those readings is masked with C++14 digit separators; when that
    pass meets a ``'`` it takes as a separator, the C17/C++11 masking (no
    separators) is scanned too, and when the legacy masking would decide a
    ``'`` or a raw prefix differently, so is that one. A ``'`` after a number
    that no reading covers (gcc, clang and MSVC each lex it differently) and
    a raw prefix with a delimiter some compiler rejects are refused wherever
    they stand in the old or the new text.

    The work is bounded: the distinct readings are counted first (cheap), and
    when there are more than two and together they would put more than
    ``_LEXING_WORK_CHARS`` characters (old plus new text, per reading)
    through the scanner, the input is refused, never accepted. The quote
    readings found while scanning count against the same bound.

    gcc, clang and MSVC skip one U+FEFF (byte order mark) at the very start of
    a file, so exactly one there is dropped from the old and the new text
    first; any other U+FEFF stays and is refused by the scan.
    """
    before = _without_bom(before)
    after = _without_bom(after)
    blank_before, odd_before = _blank_splices(before)
    blank_after, odd_after = _blank_splices(after)
    digraph_modes = (True, False) if _may_hold_digraph(before) or _may_hold_digraph(after) \
        else (True,)
    splice_modes = (False, True) if blank_before or blank_after else (False,)
    legacy = odd_before or odd_after or len(digraph_modes) == 2 \
        or "??" in str(before or "") or "??" in str(after or "")
    lexings: list[dict[str, bool]] = [
        {"trigraphs": trigraphs, "digraphs": digraphs, "strict_splices": strict_splices}
        for trigraphs in (True, False) for digraphs in digraph_modes
        for strict_splices in splice_modes]
    if legacy:
        lexings.append({"legacy": True})
    unit = len(str(before or "")) + len(str(after or "")) + 1
    done: set[tuple[bytes, bytes, bool, bool]] = set()
    plan: list[tuple[dict[str, bool], bool, bool]] = []
    for lexing in lexings:
        old = _translation_phases(before, **lexing)
        new = _translation_phases(after, **lexing)
        pairs = lexing.get("digraphs", False) \
            and any(pair in old or pair in new for pair in _LOOP_DIGRAPHS)
        old_mark, new_mark = _digest(old), _digest(new)
        for raw_strings in ((True, False) if 'R"' in old or 'R"' in new else (False,)):
            key = (old_mark, new_mark, raw_strings, pairs)
            if key not in done:
                done.add(key)
                plan.append((lexing, raw_strings, pairs))
    readings = len(plan)
    if readings > 2 and readings * unit > _LEXING_WORK_CHARS:
        return (_LEXING_REFUSAL,)
    scanned: set[bytes] = set()
    found: list[str] = []

    def note(reason: str) -> None:
        if reason not in found:
            found.append(reason)

    for lexing, raw_strings, pairs in plan:
        old = _translation_phases(before, **lexing)
        new = _translation_phases(after, **lexing)
        events: set[str] = set()
        masked = [(_mask_literals(old, raw_strings=raw_strings, digraphs=pairs, events=events),
                   _mask_literals(new, raw_strings=raw_strings, digraphs=pairs, events=events))]
        # The C17 and legacy quote readings follow the C++14 one up to the first quote they
        # decide differently, so each runs only when the C++14 pass saw such a quote.
        extra = [mode for mode, event in (("none", _EVENT_SEPARATOR), ("legacy", _EVENT_LEGACY))
                 if event in events]
        if extra:
            readings += len(extra)
            if readings > 2 and readings * unit > _LEXING_WORK_CHARS:
                note(_LEXING_REFUSAL)
                return tuple(found)
        for mode in extra:
            seen: set[str] = set()
            masked.append((
                _mask_literals(old, raw_strings=raw_strings, digraphs=pairs, separators=mode, events=seen),
                _mask_literals(new, raw_strings=raw_strings, digraphs=pairs, separators=mode, events=seen)))
            if mode == "none" and _EVENT_BAD_RAW in seen:  # C++11 has raw strings too
                events.add(_EVENT_BAD_RAW)
        # Anywhere in the old or the new text, not only in added lines: a quote or raw
        # prefix lexed differently changes which later lines are hidden in a comment.
        if _EVENT_AMBIGUOUS in events:
            note(_AMBIGUOUS_SEPARATOR)
        if _EVENT_BAD_RAW in events:
            note(_BAD_RAW_DELIMITER)
        for old_masked, new_masked in masked:
            added = _added_lines(old_masked, new_masked)
            mark = _digest(added)
            if mark in scanned:
                continue
            scanned.add(mark)
            for reason in scan_hostile_directives(added, include_ok=include_ok):
                note(reason)
    return tuple(found)


# --- patches ------------------------------------------------------------------------

@dataclass(frozen=True, slots=True)
class PatchHunk:
    file_rel: str
    anchor: str
    replacement: str

    def __post_init__(self) -> None:
        if not isinstance(self.file_rel, str) or safe_rel(self.file_rel) is None:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk file must be source-relative")
        if not isinstance(self.anchor, str) or not 1 <= len(self.anchor) <= MAX_ANCHOR_CHARS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk anchor must be 1..4000 characters")
        if not isinstance(self.replacement, str) or len(self.replacement) > MAX_REPLACEMENT_CHARS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk replacement exceeds 8000 characters")
        if "\x00" in self.anchor or "\x00" in self.replacement:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk contains NUL")


@dataclass(frozen=True, slots=True)
class CandidatePatch:
    hunks: tuple[PatchHunk, ...]
    rationale: str = ""
    model_id: str = ""

    def __post_init__(self) -> None:
        if not isinstance(self.hunks, tuple) or not 1 <= len(self.hunks) <= MAX_HUNKS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "a patch has 1..8 hunks")
        if any(not isinstance(item, PatchHunk) for item in self.hunks):
            raise BuildDomainError("FIX_SCOPE_REJECTED", "a patch holds PatchHunk items")
        if not isinstance(self.rationale, str) or len(self.rationale) > MAX_RATIONALE_CHARS:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "rationale exceeds 600 characters")
        if not isinstance(self.model_id, str) or len(self.model_id) > 200:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "model id is bounded")

    def files(self) -> tuple[str, ...]:
        out: list[str] = []
        for hunk in self.hunks:
            rel = safe_rel(hunk.file_rel) or hunk.file_rel
            if rel not in out:
                out.append(rel)
        return tuple(out)


def parse_candidate_patch(text: str, *, model_id: str = "") -> CandidatePatch:
    """Strict JSON answer ``{"hunks":[{"file","anchor","replace"}],"rationale"}``."""
    if not isinstance(text, str) or len(text) > 200_000:
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer is not bounded text")
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```(?:json)?\s*|\s*```$", "", stripped)
    try:
        document = json.loads(stripped)
    except (ValueError, RecursionError) as exc:
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer is not JSON") from exc
    if not isinstance(document, dict) or set(document) - {"hunks", "rationale"}:
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer has unexpected fields")
    hunks_raw = document.get("hunks")
    if not isinstance(hunks_raw, list):
        raise BuildDomainError("FIX_SCOPE_REJECTED", "candidate answer needs hunks")
    hunks: list[PatchHunk] = []
    for item in hunks_raw[: MAX_HUNKS + 1]:
        if not isinstance(item, dict) or set(item) - {"file", "anchor", "replace"}:
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk has unexpected fields")
        if not all(isinstance(item.get(key), str) for key in ("file", "anchor", "replace")):
            raise BuildDomainError("FIX_SCOPE_REJECTED", "hunk fields must be strings")
        hunks.append(PatchHunk(file_rel=item["file"], anchor=item["anchor"],
                               replacement=item["replace"]))
    rationale = document.get("rationale", "")
    return CandidatePatch(hunks=tuple(hunks),
                          rationale=rationale if isinstance(rationale, str) else "",
                          model_id=clip(model_id, 200))


def include_checker(scope: EditScope, file_rel: str) -> Callable[[str], bool]:
    """``include_ok`` for one edited file: quoted includes stay inside the root."""
    base = posixpath.dirname(safe_rel(file_rel) or "")

    def ok(path: str) -> bool:
        joined = posixpath.join(base, path.replace("\\", "/")) if base else path.replace("\\", "/")
        return safe_rel(joined) is not None

    return ok


def _changed_lines(before: str, after: str) -> int:
    old = before.splitlines()
    new = after.splitlines()
    changed = 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, old, new, autojunk=False).get_opcodes():
        if tag != "equal":
            changed += max(i2 - i1, j2 - j1)
    return changed


def validate_patch(
    patch: CandidatePatch,
    *,
    scope: EditScope,
    current: Mapping[str, str],
    max_changed_lines: int = MAX_PATCH_CHANGED_LINES,
    loop_changed_lines_used: int = 0,
    loop_files_used: frozenset[str] | tuple[str, ...] = frozenset(),
    max_loop_changed_lines: int = MAX_LOOP_CHANGED_LINES,
    max_loop_files: int = MAX_LOOP_FILES,
) -> tuple[dict[str, str], tuple[str, ...]]:
    """Apply a candidate in memory and check it; ``({}, reasons)`` when refused.

    ``current`` maps each file the loop read to its present text. Every hunk
    anchor must occur exactly once (after earlier hunks to the same file).
    """
    reasons: list[str] = []
    texts: dict[str, str] = {}
    for hunk in patch.hunks:
        rel = safe_rel(hunk.file_rel)
        if rel is None:
            reasons.append("OUT_OF_SCOPE_FILE: %s" % clip(hunk.file_rel, 120))
            continue
        allowed, why = scope.allows(rel)
        if not allowed:
            reasons.append("%s: %s" % (why, rel))
            continue
        if rel not in texts:
            if rel not in current:
                reasons.append("OUT_OF_SCOPE_FILE: %s was not read by the loop" % rel)
                continue
            texts[rel] = current[rel]
            if looks_generated(texts[rel]):
                reasons.append("OUT_OF_SCOPE_FILE: %s is marked generated" % rel)
                continue
        occurrences = texts[rel].count(hunk.anchor)
        if occurrences != 1:
            reasons.append("ANCHOR_%s: %s" % ("MISSING" if occurrences == 0 else "AMBIGUOUS", rel))
            continue
        texts[rel] = texts[rel].replace(hunk.anchor, hunk.replacement, 1)
    changed_total = 0
    for rel, new_text in texts.items():
        before = current.get(rel, "")
        if len(new_text.encode("utf-8", "replace")) > scope.max_file_bytes:
            reasons.append("FILE_TOO_LARGE: %s" % rel)
        changed_total += _changed_lines(before, new_text)
        # Every lexing (raw strings, trigraphs, digraphs, splice blanks): none can
        # hide a directive that a compiler reading the file the other way would see.
        found = scan_added_lexings(before, new_text, include_ok=include_checker(scope, rel))
        reasons.extend("HOSTILE_DIRECTIVE: %s: %s" % (rel, reason) for reason in found)
    touched = set(loop_files_used) | {rel for rel, text in texts.items() if text != current.get(rel)}
    if changed_total > max_changed_lines:
        reasons.append("BUDGET: patch changes %d lines (max %d)" % (changed_total, max_changed_lines))
    if loop_changed_lines_used + changed_total > max_loop_changed_lines:
        reasons.append("BUDGET: loop would change %d lines (max %d)"
                       % (loop_changed_lines_used + changed_total, max_loop_changed_lines))
    if len(touched) > max_loop_files:
        reasons.append("BUDGET: loop would touch %d files (max %d)" % (len(touched), max_loop_files))
    if not reasons and all(text == current.get(rel) for rel, text in texts.items()):
        reasons.append("NO_CHANGE: the candidate does not change any file")
    if reasons:
        return {}, tuple(reasons[:32])
    return {rel: text for rel, text in texts.items() if text != current.get(rel)}, ()


# --- progress -------------------------------------------------------------------------

@dataclass(frozen=True, slots=True)
class BuildProgress:
    build_ran: bool
    complete: bool
    errors_total: int = 0
    focus_errors: int = 0
    failed_units: int = 0
    link_errors: int = 0
    new_warnings: int = 0

    def __post_init__(self) -> None:
        for name in ("build_ran", "complete"):
            if type(getattr(self, name)) is not bool:
                raise BuildDomainError("FIX_SCOPE_REJECTED", "%s must be boolean" % name)
        for name in ("errors_total", "focus_errors", "failed_units", "link_errors", "new_warnings"):
            value = getattr(self, name)
            if type(value) is not int or value < 0:
                raise BuildDomainError("FIX_SCOPE_REJECTED", "%s must be >= 0" % name)

    @property
    def fixed(self) -> bool:
        return self.build_ran and self.complete and self.errors_total == 0 \
            and self.failed_units == 0 and self.link_errors == 0


def progress_key(v: BuildProgress) -> tuple:
    """Lexicographic keep-best order: lower is better.

    Not the strategy controller's dominance rule: a candidate that fixes
    errors but adds a warning is *better* here, while
    ``assess_progress`` over ``to_strategy_metrics`` calls it REGRESSED. The
    loop keeps the best by this key and lets the strategy see dominance.
    """
    return (not v.build_ran, not v.complete, v.failed_units, v.errors_total, v.focus_errors,
            v.link_errors, v.new_warnings)


def to_strategy_metrics(v: BuildProgress) -> tuple[tuple[str, int], ...]:
    """(name, value) pairs for domain.strategy ProgressMetric (all minimized)."""
    return (
        ("compiler_errors", v.errors_total),
        ("focus_errors", v.focus_errors),
        ("failed_units", v.failed_units),
        ("link_errors", v.link_errors),
        ("new_warnings", v.new_warnings),
    )


def progress_to_wire(v: BuildProgress | None) -> dict | None:
    if v is None:
        return None
    return {
        "build_ran": v.build_ran, "complete": v.complete, "errors_total": v.errors_total,
        "focus_errors": v.focus_errors, "failed_units": v.failed_units,
        "link_errors": v.link_errors, "new_warnings": v.new_warnings,
    }


