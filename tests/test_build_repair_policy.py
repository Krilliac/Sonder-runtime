def test_file_changes_and_fix_report_wire_are_bounded():
    before = "\n".join("line %d" % i for i in range(3000))
    after = before.replace("line 1", "LINE 1")
    changes = make_file_changes((("src/a.cpp", before, after), ("src/b.cpp", before, after)))
    assert sum(len(item.diff.encode()) for item in changes) <= 16 * 1024 + 64
    assert changes[0].before_sha256 != changes[0].after_sha256
    report = make_fix_report(status="fixed", stop_reason=FixStopReason.FIXED, job_id="build-fix-" + "0" * 16,
                             target="game", files=changes, notes=("n",) * 40,
                             initial=BuildProgress(True, True, errors_total=2),
                             best=BuildProgress(True, True))
    wire = fix_report_to_wire(report)
    assert len(json.dumps(wire).encode()) <= 48_000
    assert wire["stop_reason"] == "FIXED" and wire["digest"] == report.digest
    with pytest.raises(BuildDomainError):
        make_fix_report(status="done", stop_reason=FixStopReason.FIXED, job_id="j", target="g")
