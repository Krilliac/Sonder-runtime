def test_edit_scope_allows_sources_and_globs_only_narrow():
    assert SCOPE.allows("src/core/math.cpp") == (True, "")
    assert SCOPE.allows("src/core/math.h") == (True, "")
    narrow = EditScope(roots=("/w",), globs=("src/core/**",), excluded_rel=frozenset({"src/core/tool.cpp"}))
    assert narrow.allows("src/core/math.cpp")[0] and narrow.allows("src/core/deep/x.h")[0]
    assert narrow.allows("src/game/main.cpp") == (False, "OUT_OF_SCOPE_FILE")
    assert narrow.allows("src/core/tool.cpp") == (False, "BUILD_TIME_TOOL_SOURCE")
    widening = EditScope(roots=("/w",), globs=("**",))
    assert widening.allows("CMakeLists.txt") == (False, "NEEDS_BUILD_SCRIPT_CHANGE")
    for bad in (("/abs/**",), ("../**",), ("C:/x",), tuple("g%d" % i for i in range(17))):
        with pytest.raises(BuildDomainError):
            EditScope(roots=("/w",), globs=bad)
    with pytest.raises(BuildDomainError):
        EditScope(roots=("/a", "/b"))
    assert SCOPE.digest() != narrow.digest()


