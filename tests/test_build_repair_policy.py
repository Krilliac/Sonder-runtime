def _patch(*hunks: tuple[str, str, str]) -> CandidatePatch:
    return CandidatePatch(hunks=tuple(PatchHunk(*hunk) for hunk in hunks), model_id="fake")


def test_validate_patch_applies_a_clean_fix():
    texts, reasons = validate_patch(_patch(("src/core/math.cpp", "lenght(v)", "length(v)")),
                                    scope=SCOPE, current={"src/core/math.cpp": MATH})
    assert reasons == ()
    assert texts == {"src/core/math.cpp": MATH.replace("lenght", "length")}


def test_validate_patch_refusals():
    current = {"src/core/math.cpp": MATH + "lenght\n", "tools/shadergen.cpp": "int main(){}\n",
               "src/core/gen.h": "// generated by x\n"}
    cases = [
        (("tools/shadergen.cpp", "int main", "int  main"), "BUILD_TIME_TOOL_SOURCE"),
        (("src/core/math.cpp", "missing anchor", "x"), "ANCHOR_MISSING"),
        (("src/core/math.cpp", "lenght", "length"), "ANCHOR_AMBIGUOUS"),
        (("src/core/other.cpp", "x", "y"), "was not read"),
        (("src/core/gen.h", "x", "y"), "marked generated"),
        (("src/core/math.cpp", "float l", '#include "/etc/shadow"\nfloat l'), "HOSTILE_DIRECTIVE"),
        (("src/core/math.cpp", "    return l;", "    return l;"), "NO_CHANGE"),
    ]
    for hunk, needle in cases:
        texts, reasons = validate_patch(_patch(hunk), scope=SCOPE, current=current)
        assert texts == {} and any(needle in reason for reason in reasons), (hunk, reasons)


def test_validate_patch_budgets():
    big = "\n".join("line %d" % i for i in range(300)) + "\n"
    replacement = "\n".join("LINE %d" % i for i in range(250)) + "\n"
    texts, reasons = validate_patch(_patch(("src/a.cpp", big, replacement)), scope=SCOPE,
                                    current={"src/a.cpp": big})
    assert texts == {} and any("patch changes" in reason for reason in reasons)
    texts, reasons = validate_patch(_patch(("src/a.cpp", "line 1\n", "LINE 1\n")), scope=SCOPE,
                                    current={"src/a.cpp": big}, loop_changed_lines_used=400)
    assert texts == {} and any("loop would change" in reason for reason in reasons)
    used = frozenset({"f%d.cpp" % i for i in range(6)})
    texts, reasons = validate_patch(_patch(("src/a.cpp", "line 1\n", "LINE 1\n")), scope=SCOPE,
                                    current={"src/a.cpp": big}, loop_files_used=used)
    assert texts == {} and any("touch 7 files" in reason for reason in reasons)
    ok, reasons = validate_patch(_patch(("src/a.cpp", "line 1\n", "LINE 1\n")), scope=SCOPE,
                                 current={"src/a.cpp": big}, loop_files_used=frozenset({"src/a.cpp"}))
    assert reasons == () and ok


def test_hunk_and_patch_bounds():
    with pytest.raises(BuildDomainError):
        PatchHunk("src/a.cpp", "", "x")
    with pytest.raises(BuildDomainError):
        PatchHunk("src/a.cpp", "a" * 4001, "x")
    with pytest.raises(BuildDomainError):
        PatchHunk("src/a.cpp", "a", "x" * 8001)
    with pytest.raises(BuildDomainError):
        PatchHunk("../a.cpp", "a", "b")
    with pytest.raises(BuildDomainError):
        CandidatePatch(hunks=())
    with pytest.raises(BuildDomainError):
        CandidatePatch(hunks=tuple(PatchHunk("a.cpp", "a", "b") for _ in range(9)))


def test_progress_key_properties():
    fixed = BuildProgress(build_ran=True, complete=True)
    one_error = BuildProgress(True, True, errors_total=1, failed_units=1)
    two_errors = BuildProgress(True, True, errors_total=2, failed_units=1)
    two_units = BuildProgress(True, True, errors_total=1, failed_units=2)
    warned = BuildProgress(True, True, errors_total=1, failed_units=1, new_warnings=3)
    not_run = BuildProgress(False, False)
    partial = BuildProgress(True, False)
    order = sorted([not_run, warned, two_units, two_errors, partial, one_error, fixed], key=progress_key)
    assert order == [fixed, one_error, warned, two_errors, two_units, partial, not_run]
    assert fixed.fixed and not one_error.fixed
    with pytest.raises(BuildDomainError):
        BuildProgress(True, True, errors_total=-1)


def _vector(progress: BuildProgress) -> ProgressVector:
    return ProgressVector(scope_digest="a" * 64, metrics=tuple(
        ProgressMetric(name, float(value)) for name, value in to_strategy_metrics(progress)))


def test_strategy_dominance_differs_from_keep_best_when_a_warning_appears():
    before = BuildProgress(True, True, errors_total=3, focus_errors=2, failed_units=2)
    after = BuildProgress(True, True, errors_total=1, focus_errors=0, failed_units=1, new_warnings=1)
    assert progress_key(after) < progress_key(before)  # keep-best: improved
    assert assess_progress(_vector(before), _vector(after)) is ProgressAssessment.REGRESSED
    names = [name for name, _ in to_strategy_metrics(after)]
    assert names == ["compiler_errors", "focus_errors", "failed_units", "link_errors", "new_warnings"]


