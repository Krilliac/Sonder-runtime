    by_offset = {item.offset: item for item in findings.symbolized}
    assert by_offset[0x1006].frames[0].function == "main" and by_offset[0x1006].frames[0].line == 9
    assert by_offset[0x1003].frames[0].function == "helper"
    assert by_offset[0x1003].frames[0].file == "C:\\agent\\_work\\3\\s\\src\\spark_tiny.c"
