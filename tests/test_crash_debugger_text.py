def test_cdb_access_violation_transcript():
    findings = parse_cdb(_text("cdb_av.txt"), NONCE)
    assert findings.crashing_thread == 0x1B3C
    top = findings.frames_for(0x1B3C)[0]
    assert (top.module, top.function, top.file, top.line) == (
        "spark_game", "Renderer::Submit", "C:\\agent\\_work\\3\\s\\Engine\\Render\\render.cpp", 42)
    exc = findings.exception
    assert exc.name == "EXCEPTION_ACCESS_VIOLATION" and exc.access == "read" and exc.access_address == 8
    assert dict(findings.thread_names)[0x1B3C] == "MainThread"
    worker = findings.frames_for(0x2200)
    assert worker[0].function == "NtWaitForSingleObject"
    assert [m.name for m in findings.modules] == ["spark_game.exe", "render.dll", "ntdll.dll"]
    assert any("NULL_CLASS_PTR_READ" in note for note in findings.notes)


